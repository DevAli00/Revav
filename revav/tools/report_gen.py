# ---------------------------------------------------------------------------
# Core logic
# ---------------------------------------------------------------------------


def load_product_profile(profile_path: Path) -> dict:
    """Load a product profile YAML file."""
    with open(profile_path) as f:
        return yaml.safe_load(f)


def load_analysis_data(profile: dict, kb_root: Path) -> dict:
    """Load all analysis artifacts referenced by the product profile."""
    data: dict = {"profile": profile}
    product_name = profile.get("product_name", "unknown")

    catalog_path = kb_root / "catalog" / f"{product_name}.json"
    if catalog_path.exists():
        with open(catalog_path) as f:
            data["catalog"] = json.load(f)

    layer_path = kb_root / "layers" / f"{product_name}.json"
    if layer_path.exists():
        with open(layer_path) as f:
            data["coverage"] = json.load(f)

    return data


def generate_bypass_brief(
    profile: dict,
    analysis: dict,
    version: str = "0.1.0",
) -> GeneratedReport:
    """Generate a bypass brief for red team operators."""
    product_name = profile.get("product_name", "Unknown Product")
    coverage = analysis.get("coverage", {})

    overall_score = coverage.get("overall_score", 0)
    blind_spots = coverage.get("blind_spots", [])
    techniques = coverage.get("technique_scores", [])

    grade = "A" if overall_score >= 90 else "B" if overall_score >= 70 else "C" if overall_score >= 50 else "D" if overall_score >= 30 else "F"

    blind_spots_lines = []
    for bs in blind_spots:
        blind_spots_lines.append(
            f"### {bs.get('technique_id', '?')} — {bs.get('weakness_class', '?')}\n\n"
            f"**Severity:** {bs.get('severity', 'unknown')}\n"
            f"**Feasibility:** {bs.get('bypass_feasibility', 'unknown')}\n\n"
            f"{bs.get('description', '')}\n"
        )

    mechanism_counts: dict[str, int] = {}
    for t in techniques:
        for m in t.get("mechanisms", []):
            mt = m.get("mechanism_type", "unknown")
            mechanism_counts[mt] = mechanism_counts.get(mt, 0) + 1

    mech_rows = []
    quality_map = {"callback": "High", "hook": "Medium-High", "behavioral": "Medium", "rule": "Medium", "telemetry": "Low"}
    for mtype, count in sorted(mechanism_counts.items()):
        quality = quality_map.get(mtype, "Unknown")
        mech_rows.append(f"| {mtype} | {count} | {quality} |")

    remediation_lines = []
    for bs in blind_spots:
        rem = bs.get("remediation", "")
        if rem:
            remediation_lines.append(f"- **{bs.get('technique_id', '?')}**: {rem}")

    critical_count = sum(1 for bs in blind_spots if bs.get("severity") == "critical")

    markdown = BYPASS_BRIEF_TEMPLATE.format(
        product_name=product_name,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        version=version,
        overall_score=overall_score,
        grade=grade,
        blind_spot_count=len(blind_spots),
        critical_count=critical_count,
        blind_spots_section="\n".join(blind_spots_lines) or "No blind spots identified.",
        mechanism_table="\n".join(mech_rows) or "| (none) | 0 | N/A |",
        coverage_heatmap="*(See companion ATT&CK Navigator layer)*",
        remediation_section="\n".join(remediation_lines) or "No remediation items.",
    )

    return GeneratedReport(
        format=ReportFormat.BYPASS_BRIEF,
        product_name=product_name,
        title=f"Bypass Brief: {product_name}",
        markdown=markdown,
    )


def generate_eval_scorecard(
    profile: dict,
    analysis: dict,
    version: str = "0.1.0",
) -> GeneratedReport:
    """Generate an evaluation scorecard for security architects."""
    product_name = profile.get("product_name", "Unknown Product")
    coverage = analysis.get("coverage", {})

    overall_score = coverage.get("overall_score", 0)
    grade_dist = coverage.get("grade_distribution", {})
    total = sum(grade_dist.values()) or 1

    grade_rows = []
    for grade in ["A", "B", "C", "D", "F"]:
        count = grade_dist.get(grade, 0)
        pct = round(count / total * 100, 1)
        grade_rows.append(f"| {grade} | {count} | {pct}% |")

    markdown = EVAL_SCORECARD_TEMPLATE.format(
        product_name=product_name,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        version=version,
        overall_score=overall_score,
        grade_table="\n".join(grade_rows),
        tactic_coverage="*(Run `revav analyze` to populate tactic coverage)*",
        mechanism_quality="*(Run `revav scan` to populate mechanism data)*",
        comparison_notes="*(Run `revav compare` to add competitive context)*",
    )

    return GeneratedReport(
        format=ReportFormat.EVAL_SCORECARD,
        product_name=product_name,
        title=f"Evaluation Scorecard: {product_name}",
        markdown=markdown,
    )


def generate_report(
    profile_path: Path,
    report_format: ReportFormat,
    kb_root: Path | None = None,
) -> GeneratedReport:
    """Generate a report in the specified format."""
    if kb_root is None:
        kb_root = profile_path.parent.parent

    profile = load_product_profile(profile_path)
    analysis = load_analysis_data(profile, kb_root)

    if report_format == ReportFormat.BYPASS_BRIEF:
        return generate_bypass_brief(profile, analysis)
    elif report_format == ReportFormat.EVAL_SCORECARD:
        return generate_eval_scorecard(profile, analysis)
    elif report_format == ReportFormat.VENDOR_AUDIT:
        # TODO: implement vendor audit report
        return GeneratedReport(
            format=report_format,
            product_name=profile.get("product_name", "unknown"),
            title="Vendor Audit",
            markdown="# Vendor Audit\n\n*Not yet implemented*",
        )
    else:
        # Full report: combine all formats
        bypass = generate_bypass_brief(profile, analysis)
        scorecard = generate_eval_scorecard(profile, analysis)
        return GeneratedReport(
            format=ReportFormat.FULL,
            product_name=profile.get("product_name", "unknown"),
            title=f"Full Analysis: {profile.get('product_name', 'unknown')}",
            markdown=bypass.markdown + "\n\n---\n\n" + scorecard.markdown,
        )


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


@click.command()
@click.option("--profile", "-p", required=True, help="Product profile YAML path")
@click.option(
    "--format", "-f", "report_format",
    type=click.Choice(["bypass-brief", "eval-scorecard", "vendor-audit", "full"]),
    default="full",
    help="Report format",
)
@click.option("--output", "-o", default=None, help="Output file path (default: stdout)")
@click.option("--kb-root", default=None, help="Knowledge base root directory")
def main(profile: str, report_format: str, output: str | None, kb_root: str | None) -> None:
    """Generate analysis reports from Revav knowledge base."""
    fmt = ReportFormat(report_format)
    kb = Path(kb_root) if kb_root else None

    report = generate_report(Path(profile), fmt, kb)

    if output:
        Path(output).write_text(report.markdown)
        click.echo(f"Report written to {output}")
    else:
        click.echo(report.markdown)


if __name__ == "__main__":
    main()
