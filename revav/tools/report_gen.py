"""Report Generator — Produces human-readable reports from Revav analysis data.

Generates bypass briefs (red team), evaluation scorecards (blue team),
vendor claim audits (procurement), and full analysis reports from the
knowledge base artifacts.

Output: Markdown reports rendered from Jinja2 templates.
"""

from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path

import click
import yaml
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Data models
# ---------------------------------------------------------------------------


class ReportFormat(str, Enum):
    """Available report formats."""

    BYPASS_BRIEF = "bypass-brief"
    EVAL_SCORECARD = "eval-scorecard"
    VENDOR_AUDIT = "vendor-audit"
    FULL = "full"


class ReportSection(BaseModel):
    """A section in a generated report."""

    title: str
    content: str
    subsections: list[ReportSection] = Field(default_factory=list)


class GeneratedReport(BaseModel):
    """A fully generated report ready for output."""

    report_id: str = Field(default="")
    format: ReportFormat
    product_name: str
    generated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    title: str = Field(default="")
    sections: list[ReportSection] = Field(default_factory=list)
    markdown: str = Field(default="", description="Complete rendered Markdown")
    source_files: list[str] = Field(default_factory=list)
    errors: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Template rendering
# ---------------------------------------------------------------------------

